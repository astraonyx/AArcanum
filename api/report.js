module.exports = async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method === 'GET') {
    return res.status(200).json({
      ok: true,
      status: 'online',
      service: 'Arcanum — Feedback & Report Center (Vercel Collector)',
      total_reports: submittedReportsFeed.length,
      reports: submittedReportsFeed.slice(0, 50)
    });
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ ok: false, error: 'Method Not Allowed' });
  }

  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : (req.body || {});
    const userEmail = String(body.user_email || '').trim();
    const userName = String(body.user_name || '').trim();
    const subject = String(body.subject || '').trim();
    const message = String(body.message || '').trim();
    const category = String(body.submission_category || 'General Feedback').trim();

    // Enforce Google Account verification before accepting submission
    if (!userEmail || !userEmail.includes('@') || !userName) {
      return res.status(401).json({
        ok: false,
        error: 'Autentikasi Akun Google Diperlukan: Wajib login dengan Akun Google sebelum mengirim laporan.'
      });
    }

    if (subject.length < 5 || message.length < 20) {
      return res.status(400).json({
        ok: false,
        error: 'Anti-Spam Filter: Subjek minimal 5 karakter dan pesan minimal 20 karakter.'
      });
    }

    const entropy = calculateShannonEntropy(`${subject} ${message}`);
    if (entropy < 2.35 || /(.)\1{4,}/i.test(subject + message)) {
      return res.status(422).json({
        ok: false,
        error: 'Anti-Spam Filter: Terdeteksi ketikan acak (keysmash) atau pengulangan karakter.'
      });
    }

    const ip = req.headers['x-forwarded-for'] || 'global';
    const now = Date.now();
    const lastTs = ipTimestamps.get(ip) || 0;
    if (now - lastTs < 45000) {
      return res.status(429).json({
        ok: false,
        error: 'Anti-Spam Cooldown: Harap tunggu 60 detik antar pengiriman laporan.'
      });
    }

    const normalized = `${category.toLowerCase()}|${subject.toLowerCase()}|${message.toLowerCase()}`
      .replace(/[^a-z0-9\s]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    const contentHash = crypto.createHash('sha256').update(normalized).digest('hex').slice(0, 24);

    if (recentHashes.has(contentHash)) {
      return res.status(409).json({
        ok: false,
        error: `Anti-Spam Deduplicator: Laporan duplikat terdeteksi (SHA-256: ${contentHash}).`
      });
    }

    ipTimestamps.set(ip, now);
    recentHashes.add(contentHash);

    const formattedDocument = formatArcanumReport(body);

    const entry = {
      submission_id: body.submission_id || ('ARC-' + Date.now()),
      submission_date: body.submission_date || new Date().toISOString().slice(0, 10),
      submission_time: body.submission_time || new Date().toTimeString().slice(0, 8),
      user_name: userName,
      user_id: body.user_id || 'USR-GGL-VERIFIED',
      user_email: userEmail,
      submission_category: category,
      priority: body.priority || 'Normal',
      subject,
      message,
      device_model: body.device_model || 'Vercel Web Client',
      android_version: body.android_version || 'Web Runtime',
      attachment_url: body.attachment_url || 'None',
      content_hash: contentHash,
      entropy: Number(entropy.toFixed(2)),
      formatted_markdown: formattedDocument,
      status: 'Received'
    };

    submittedReportsFeed.unshift(entry);
    if (submittedReportsFeed.length > 100) {
      submittedReportsFeed.pop();
    }

    // Emit structured report to Vercel Function Logs so it is always detectable in Vercel Dashboard
    console.log('=== [ARCANUM_REPORT_RECEIVED] ===\n' + formattedDocument + '\n=== [/ARCANUM_REPORT_RECEIVED] ===');

    return res.status(200).json({
      ok: true,
      submission_id: entry.submission_id,
      content_hash: contentHash,
      entropy: entry.entropy,
      formatted_markdown: formattedDocument,
      status: 'Received'
    });
  } catch (err) {
    return res.status(500).json({
      ok: false,
      error: 'Internal Server Error: ' + (err && err.message ? err.message : 'Unknown')
    });
  }
};
